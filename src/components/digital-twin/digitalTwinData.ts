/**
 * Calculates POI flood status dynamically based on current water level
 */
export function calculatePoiStatus(poi: InfrastructurePOI, currentSurgeMeters: number): {
  floodDepth: number;
  status: "safe" | "warning" | "critical" | "flooded";
} {
  const waterElevation = currentSurgeMeters;
  const groundElevation = poi.elevationMsl;
  const floodDepth = Math.max(0, parseFloat((waterElevation - groundElevation).toFixed(2)));

  if (floodDepth <= 0) {
    return { floodDepth: 0, status: "safe" };
  } else if (floodDepth < 0.4) {
    return { floodDepth, status: "warning" };
  } else if (floodDepth < 1.2) {
    return { floodDepth, status: "critical" };
  } else {
    return { floodDepth, status: "flooded" };
  }
}

